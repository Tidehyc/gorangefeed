// flushPendingOutboxNotifications extracts pending outbox events generated by user actions
// and drives them through the Notification Consumer and outbox state transition.
func flushPendingOutboxNotifications(t *testing.T, ctxExt *e2eExtendedCtx) int {
	t.Helper()

	var events []persistenceoutbox.OutboxModel
	err := ctxExt.DB.Where("event_type IN ? AND status = ?", []string{
		"interaction.liked",
		"interaction.commented",
		"relation.followed",
	}, "pending").Order("id ASC").Find(&events).Error
	if err != nil {
		t.Fatalf("failed to query pending outbox events: %v", err)
	}

	for _, e := range events {
		err := ctxExt.Consumer.HandleEvent(context.Background(), e.EventID, e.EventType, e.Payload)
		if err != nil {
			t.Fatalf("failed to dispatch outbox event %s (%s): %v", e.EventID, e.EventType, err)
		}
		now := time.Now()
		ctxExt.DB.Model(&persistenceoutbox.OutboxModel{}).
			Where("id = ?", e.ID).
			Updates(map[string]interface{}{
				"status":  "sent",
				"sent_at": &now,
			})
	}
	return len(events)
}

// sseReceivedMessage represents an individual W3C SSE message frame.
type sseReceivedMessage struct {
	ID      string
	Event   string
	Data    string
	Comment string
	Retry   int
}

// readNextSSEMessage reads the next message block from an SSE stream.
func readNextSSEMessage(reader *bufio.Reader, timeout time.Duration) (*sseReceivedMessage, error) {
	type readResult struct {
		msg *sseReceivedMessage
		err error
	}
	ch := make(chan readResult, 1)

	go func() {
		msg := &sseReceivedMessage{}
		hasFields := false
		for {
			line, err := reader.ReadString('\n')
			if err != nil {
				if hasFields {
					ch <- readResult{msg: msg}
					return
				}
				ch <- readResult{err: err}
				return
			}
			line = strings.TrimRight(line, "\r\n")
			if line == "" {
				if hasFields {
					ch <- readResult{msg: msg}
					return
				}
				continue
			}
			hasFields = true
			if strings.HasPrefix(line, ":") {
				msg.Comment = strings.TrimSpace(strings.TrimPrefix(line, ":"))
			} else if strings.HasPrefix(line, "id: ") {
				msg.ID = strings.TrimPrefix(line, "id: ")
			} else if strings.HasPrefix(line, "event: ") {
				msg.Event = strings.TrimPrefix(line, "event: ")
			} else if strings.HasPrefix(line, "data: ") {
				msg.Data = strings.TrimPrefix(line, "data: ")
			} else if strings.HasPrefix(line, "retry: ") {
				msg.Retry, _ = strconv.Atoi(strings.TrimPrefix(line, "retry: "))
			}
		}
	}()

	select {
	case res := <-ch:
		return res.msg, res.err
	case <-time.After(timeout):
		return nil, fmt.Errorf("timeout waiting for SSE message after %v", timeout)
	}
}

// readNextNotification consumes SSE frames until an 'event: notification' frame is found.
func readNextNotification(reader *bufio.Reader, timeout time.Duration) (*sseReceivedMessage, error) {
	deadline := time.Now().Add(timeout)
	for {
		remaining := time.Until(deadline)
		if remaining <= 0 {
			return nil, errors.New("timed out waiting for notification event")
		}
		msg, err := readNextSSEMessage(reader, remaining)
		if err != nil {
			return nil, err
		}
		if msg.Event == "notification" {
			return msg, nil
		}
	}
}

